    private static Geometry ParseMirrored(string path, double axis)
    {
        Geometry geometry = Geometry.Parse(path);

        geometry.Transform = new MatrixTransform(new Matrix(-1, 0, 0, 1, axis, 0));

        return geometry;
    }

    private static Geometry ParseOutline(string path, double thickness)
    {
        Geometry stroke = Geometry.Parse(path);

        return stroke.GetWidenedGeometry(new Pen(Brushes.Black, thickness));
    }

    private static Geometry CreateUnion(params Geometry[] parts)
    {
        Geometry result = parts[0];

        for (int index = 1; index < parts.Length; index++)
        {
            result = new CombinedGeometry(GeometryCombineMode.Union, result, parts[index]);
        }

        return result;
    }

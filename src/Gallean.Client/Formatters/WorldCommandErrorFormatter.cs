using Gallean.Engine;

namespace Gallean.Client;

internal static class WorldCommandErrorFormatter
{
    public static string Format(WorldCommandError error)
    {
        return error switch
        {
            WorldCommandError.BagNotFound => Tr("There is no bag at that location"),
            WorldCommandError.BattleNotFinished => Tr("The battle is not over"),
            WorldCommandError.BuildingAlreadyConstructedThisTurn => Tr("You have already constructed a building this turn"),
            WorldCommandError.BuildingAlreadyExists => Tr("This building has already been constructed"),
            WorldCommandError.BuildingBranchLocked => Tr("Another branch has already been selected"),
            WorldCommandError.BuildingMissingPrerequisite => Tr("Build the required building first"),
            WorldCommandError.BuildingNotFound => Tr("This building is no longer available"),
            WorldCommandError.CapitalNotFound => Tr("Your capital is no longer available"),
            WorldCommandError.CityAlreadyGrownThisTurn => Tr("A city can only be upgraded once per turn"),
            WorldCommandError.CityFullyUpgraded => Tr("The city cannot be upgraded any further"),
            WorldCommandError.CityRioting => Tr("You cannot take any action in this city while it is rioting"),
            WorldCommandError.DiplomacyAllianceBreakForbidden => Tr("This alliance cannot be broken"),
            WorldCommandError.DiplomacyAllianceRequired => Tr("You are not allied with that race"),
            WorldCommandError.DiplomacyAlreadyAllied => Tr("You are already allied with that race"),
            WorldCommandError.DiplomacyAlreadyProposed => Tr("You have already made this offer this turn"),
            WorldCommandError.DiplomacyGiftInvalid => Tr("Invalid amount of gold"),
            WorldCommandError.DiplomacyPeaceRequired => Tr("You must be at peace with the race to do this"),
            WorldCommandError.DiplomacyPriceInvalid => Tr("Invalid price"),
            WorldCommandError.DiplomacyProposalNotFound => Tr("This offer is no longer open"),
            WorldCommandError.DiplomacySpellNotTradable => Tr("Summon spells cannot be traded"),
            WorldCommandError.DiplomacyTargetInvalid => Tr("You cannot negotiate with that player"),
            WorldCommandError.EquipmentSlotEmpty => Tr("The equipment slot is empty"),
            WorldCommandError.EquipmentSlotOccupied => Tr("The equipment slot is occupied"),
            WorldCommandError.FortificationCaptureForbidden => Tr("Summoned creatures and thieves cannot capture a city"),
            WorldCommandError.FortificationExitBlocked => Tr("There is no free tile outside the city gate"),
            WorldCommandError.FortificationNotFound => Tr("This city or capital is no longer available"),
            WorldCommandError.GarrisonCapacityExceeded => Tr("The city is not large enough to hold more units"),
            WorldCommandError.GarrisonNotFound => Tr("This garrison is no longer available"),
            WorldCommandError.GuardianDisbandForbidden => Tr("The guardian cannot be dismissed"),
            WorldCommandError.GuardianTransferForbidden => Tr("The guardian cannot be transferred"),
            WorldCommandError.GuildBuildingRequired => Tr("Guild must be built in your capital"),
            WorldCommandError.HealBuildingRequired => Tr("Temple must be built in your capital"),
            WorldCommandError.InsufficientMovement => Tr("Not enough movement points"),
            WorldCommandError.InsufficientResources => Tr("Not enough resources"),
            WorldCommandError.InvalidUnitPosition => Tr("Invalid position"),
            WorldCommandError.ItemNotAvailable => Tr("This item is not available"),
            WorldCommandError.ItemAlreadyUsedThisTurn => Tr("This item cannot be used again this turn"),
            WorldCommandError.ItemNotFound => Tr("This item is no longer available"),
            WorldCommandError.ItemNotUsable => Tr("The item cannot be used"),
            WorldCommandError.ItemSlotMismatch => Tr("The item cannot go in that slot"),
            WorldCommandError.ItemTargetInvalid => Tr("This item cannot be used on that target"),
            WorldCommandError.LeaderDisbandForbidden => Tr("The party leader cannot be disbanded"),
            WorldCommandError.LeadershipExceeded => Tr("The party does not have enough leadership"),
            WorldCommandError.LeaderTransferForbidden => Tr("The leader cannot be transferred"),
            WorldCommandError.LeaderUpgradeNotAvailable => Tr("The leader cannot learn this ability"),
            WorldCommandError.LeaderUpgradeNotPending => Tr("This leader has no upgrades available"),
            WorldCommandError.MissingLeaderAbility => Tr("The leader lacks the ability to use this item"),
            WorldCommandError.MultipleLeadersForbidden => Tr("Only one leader is allowed in a party"),
            WorldCommandError.NoPlayersRemaining => Tr("No human-controlled players remain"),
            WorldCommandError.NotAiTurn => Tr("It is not the computer player's turn"),
            WorldCommandError.NotPlayerTurn => Tr("Not your turn"),
            WorldCommandError.PathNotFound => Tr("The party cannot reach that location"),
            WorldCommandError.RodInvalidLocation => Tr("A rod cannot be planted there"),
            WorldCommandError.RodNotFound => Tr("There is no rod at that location"),
            WorldCommandError.RodLeaderDead => Tr("The party leader must be alive to plant a rod"),
            WorldCommandError.RodLeaderRequired => Tr("Only a leader with the Rod Planting ability can plant rods"),

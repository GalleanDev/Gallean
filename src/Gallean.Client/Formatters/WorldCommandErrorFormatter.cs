            WorldCommandError.StackNotAtSite => Tr("The party is not at this site"),
            WorldCommandError.StackNotAtTrainer => Tr("The party is not at a training camp"),
            WorldCommandError.StackNotFound => Tr("This party is no longer available"),
            WorldCommandError.StackNotInCity => Tr("The party is not in one of your cities"),
            WorldCommandError.TargetOccupied => Tr("The slot is occupied"),
            WorldCommandError.TargetOutOfBounds => Tr("Out of bounds"),
            WorldCommandError.TargetTooFar => Tr("Too far"),
            WorldCommandError.TargetUnpassable => Tr("Impassable terrain"),
            WorldCommandError.ThiefActionNotAllowed => Tr("This thief action is not available to your lord"),
            WorldCommandError.ThiefLeaderRequired => Tr("Only a thief can perform this action"),
            WorldCommandError.ThiefNothingToSteal => Tr("There is nothing to steal"),
            WorldCommandError.ThiefTargetAlreadyKnown => Tr("You already have information about this target"),
            WorldCommandError.ThiefTargetInvalid => Tr("This action cannot be performed on that target"),
            WorldCommandError.UnitAlreadyTrained => Tr("The unit is already trained and will upgrade at the end of its next battle"),
            WorldCommandError.UnitDead => Tr("The unit is dead and must be resurrected"),
            WorldCommandError.UnitFullyTrained => Tr("The unit has reached its maximum experience level and can no longer benefit from training"),
            WorldCommandError.UnitHealForbidden => Tr("The unit cannot be healed"),
            WorldCommandError.UnitMissingPrerequisite => Tr("Build the required building first"),
            WorldCommandError.UnitModifierAlreadyApplied => Tr("This unit has already used this potion"),
            WorldCommandError.UnitNotAvailable => Tr("This unit is not available"),
            WorldCommandError.UnitNotDead => Tr("The unit is not dead"),
            WorldCommandError.UnitNotFound => Tr("This unit is no longer available"),
            WorldCommandError.UnitNotWounded => Tr("The unit is not wounded"),
            WorldCommandError.UnitResurrectForbidden => Tr("The unit cannot be resurrected"),
            WorldCommandError.UnitTrainingForbidden => Tr("The unit cannot be trained"),
            WorldCommandError.UnitTypeLockForbidden => Tr("The type of this unit cannot be locked")
        };
    }
}

            WorldCommandError.SpellAlreadyCastThisTurn => Tr("This spell has already been cast this turn"),
            WorldCommandError.SpellAlreadyKnown => Tr("This spell is already known"),
            WorldCommandError.SpellAlreadyResearchedThisTurn => Tr("You have already researched a spell this turn"),
            WorldCommandError.SpellBuildingRequired => Tr("Magic tower must be built in your capital"),
            WorldCommandError.SpellNotAvailable => Tr("This spell is not available"),
            WorldCommandError.SpellNotCastable => Tr("This spell cannot be cast"),

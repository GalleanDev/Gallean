using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Umbra.Backgrounds.Generators;

[Generator]
public class BackgroundGenerator : IIncrementalGenerator
{
    private sealed record ImageMetadata(string Background, string Layer, string Path);

    private static readonly string[] Layers = ["color", "normal", "depth", "albedo"];

    private static readonly Regex NamePattern = new("^[a-z][a-z0-9]*(-[a-z0-9]+)*(/[a-z0-9]+(-[a-z0-9]+)*)*$", RegexOptions.CultureInvariant);

    private static readonly DiagnosticDescriptor MissingImageDescriptor = new(
        "GALBKG001",
        "Background is missing an image",
        "Background '{0}' has no '{1}' layer",
        "Umbra.Backgrounds.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor UnexpectedImageDescriptor = new(
        "GALBKG002",
        "Background has an unexpected image",
        "Background '{0}' has an unexpected '{1}' layer",
        "Umbra.Backgrounds.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor InvalidNameDescriptor = new(
        "GALBKG003",
        "Background has an invalid name",
        "Background directory '{0}' name should consist of lowercase letters, digits and single dashes",
        "Umbra.Backgrounds.Generators",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ImageMetadata> images = context.AdditionalTextsProvider
            .Where(static text => Path.GetExtension(text.Path) == ".webp")
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (source, _) => GetMetadata(source.Left, source.Right));

        IncrementalValueProvider<string> rootNamespace = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) =>
            {
                options.GlobalOptions.TryGetValue("build_property.RootNamespace", out string? value);

                return value ?? "Umbra.Backgrounds";
            });

        context.RegisterSourceOutput(images.Collect().Combine(rootNamespace), static (spc, source) => Generate(spc, source.Left, source.Right));
    }

    private static ImageMetadata GetMetadata(AdditionalText text, AnalyzerConfigOptionsProvider options)
    {
        options.GetOptions(text).TryGetValue("build_metadata.AdditionalFiles.Background", out string? background);

        return new ImageMetadata(background ?? string.Empty, Path.GetFileNameWithoutExtension(text.Path), text.Path);
    }

    private static void Generate(SourceProductionContext context, ImmutableArray<ImageMetadata> images, string rootNamespace)
    {
        List<string> backgrounds = [];

        foreach (IGrouping<string, ImageMetadata> background in images
            .GroupBy(image => image.Background, StringComparer.Ordinal)
            .OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            if (Validate(context, background))
            {
                backgrounds.Add(background.Key);
            }
        }

        CodeWriter cw = new();

        cw.AppendLine("// <auto-generated/>");
        cw.AppendLine("#nullable enable");
        cw.AppendLine();
        cw.AppendLine("using System.Collections.Generic;");
        cw.AppendLine();
        cw.AppendLine($"namespace {rootNamespace};");
        cw.AppendLine();

        using (cw.Block("public static partial class UmbraBackgroundLibrary"))
        {
            cw.AppendLine($"public static IReadOnlyList<string> Names {{ get; }} = [{string.Join(", ", backgrounds.Select(background => $"\"{background}\""))}];");
        }

        context.AddSource("Backgrounds.g.cs", SourceText.From(cw.ToString(), Encoding.UTF8));
    }

    private static bool Validate(SourceProductionContext context, IGrouping<string, ImageMetadata> background)
    {
        List<ImageMetadata> images = background.OrderBy(image => image.Layer, StringComparer.Ordinal).ToList();
        List<string> layers = GetExpectedLayers(images);
        Location location = GetLocation(images[0]);
        bool valid = true;

        if (!NamePattern.IsMatch(background.Key))
        {
            context.ReportDiagnostic(Diagnostic.Create(InvalidNameDescriptor, location, background.Key));
            valid = false;
        }

        foreach (ImageMetadata image in images)
        {
            if (!layers.Contains(image.Layer))
            {
                context.ReportDiagnostic(Diagnostic.Create(UnexpectedImageDescriptor, GetLocation(image), background.Key, image.Layer));
                valid = false;
            }
        }

        foreach (string layer in layers)
        {
            if (images.All(image => image.Layer != layer))
            {
                context.ReportDiagnostic(Diagnostic.Create(MissingImageDescriptor, location, background.Key, layer));
                valid = false;
            }
        }

        return valid;
    }

    private static List<string> GetExpectedLayers(List<ImageMetadata> images)
    {
        HashSet<string> existing = new(StringComparer.Ordinal);

        foreach (ImageMetadata image in images)
        {
            existing.Add(image.Layer);
        }

        List<string> layers = [.. Layers];

        for (int index = 0;; index++)
        {
            string name = $"fluid{index}";

            if (existing.Contains(name))
            {
                layers.Add(name);
            }
            else
            {
                break;
            }
        }

        return layers;
    }

    private static Location GetLocation(ImageMetadata image)
    {
        return Location.Create(image.Path, default, default);
    }
}
